    private void jButtonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGuardarActionPerformed
        // TODO add your handling code here:

        try {

            int numero = Integer.parseInt(jTextFieldNumero.getText());
            String nombre = jTextFieldNombre.getText().trim();
            float puntos = Float.parseFloat(jTextFieldPuntos.getText());
            LocalDate fecha = LocalDate.parse(jTextFieldNacimiento.getText());

            if (nombre.isEmpty()) {
                jLabelError.setText("Introduzca un nombre");
                return;
            }

            if (!ControlErrores.comprobarPuntos(puntos, jLabelError)) {
                return;
            }

            if (!ControlErrores.comprobarFecha(fecha, jLabelError)) {
                return;
            }

            Cliente cliente = new Cliente(numero, nombre, puntos, fecha);

            listaClientes.anadirCliente(cliente);

            jLabelError.setText("");

            JOptionPane.showMessageDialog(this, "Cliente añadido correctamente");

            limpiar();

            alGuardar.run();

        } catch (NumberFormatException e) {

            jLabelError.setText("Número o puntos incorrectos");

        } catch (java.time.format.DateTimeParseException e) {

            jLabelError.setText("Fecha incorrecta. Usa AAAA-MM-DD");

        }

    }//GEN-LAST:event_jButtonGuardarActionPerformed


