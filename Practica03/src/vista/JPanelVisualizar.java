    public void actualizar() {

        Cliente cliente = listaClientes.obtenerClienteActual();

        if (cliente == null) {

            jTextFieldNumero.setText("");
            jTextFieldNombre.setText("");
            jTextFieldPuntos.setText("");
            jTextFieldNacimiento.setText("");

        } else {

            jTextFieldNumero.setText(String.valueOf(cliente.getNumero()));
            jTextFieldNombre.setText(cliente.getNombre());
            jTextFieldPuntos.setText(String.valueOf(cliente.getPuntos()));
            jTextFieldNacimiento.setText(String.valueOf(cliente.getFechaNacimiento()));

        }

        jButtonPrimero.setEnabled(!listaClientes.esVacia() && !listaClientes.esPrimero());
        jButtonAnterior.setEnabled(!listaClientes.esVacia() && !listaClientes.esPrimero());
        jButtonSiguiente.setEnabled(!listaClientes.esVacia() && !listaClientes.esUltimo());
        jButtonUltimo.setEnabled(!listaClientes.esVacia() && !listaClientes.esUltimo());
        jButtonBorrar.setEnabled(!listaClientes.esVacia());
        
    }

